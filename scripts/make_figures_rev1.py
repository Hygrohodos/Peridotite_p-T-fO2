def exp_fit():
    e = pe.temperatures(pe.assemble())
    e = e[e["usable"]].copy()
    w = xc.weights(e, "invvar", 50.0)
    f = xc.wls(e["T_TA98"].to_numpy(float), e["dT_Fe2"].to_numpy(float), w, 1)
    return e, w, f


def fig04_weighted(e, w, f):
    """Fig. 4 redefined: experiments with the weighted calibration (point 1)."""
    fig, ax = plt.subplots(figsize=(119 / 25.4, 95 / 25.4))
    ax.axhline(0, color="0.6", lw=0.7)
    tt = np.linspace(TLO, THI, 100)
    lo, hi = xc.band_cov(f, tt)
    ax.fill_between(tt, lo, hi, color="0.85", lw=0, zorder=1, label="95 % confidence band")
    ax.plot(tt, xc.predict(f, tt), color="k", lw=1.4, zorder=2, label="Weighted fit (13 experiments)")
    rel = w / w.max()
    for ref, sty in pe.STYLE.items():
        s = e["Reference"] == ref
        if not s.any():
            continue
        ax.scatter(e.loc[s, "T_TA98"], e.loc[s, "dT_Fe2"], s=20 + 70 * rel[s.to_numpy()],
                   edgecolors="k", linewidths=0.4, zorder=3, **sty)
        fail = s & (e["screen_pass"] != True)
        ax.scatter(e.loc[fail, "T_TA98"], e.loc[fail, "dT_Fe2"], marker="x", s=60,
                   c="k", linewidths=1.0, zorder=4)
        for _, r in e[s].iterrows():
            ax.annotate(str(r["SampleID"]), (r["T_TA98"], r["dT_Fe2"]), fontsize=6,
                        xytext=(4, 3), textcoords="offset points")
    b0, b1 = f["beta"][0], f["beta"][1]
    se = np.sqrt(np.diag(f["cov"]))
    ax.set_title(
            rf"$T_{{\mathrm{{TA98}}}}-T_{{\mathrm{{WZ07}}}}$ = {b0:.0f} ($\pm${se[0]:.0f}) "
            rf"{b1:+.3f} ($\pm${se[1]:.3f})($T_{{\mathrm{{TA98}}}}$ − 1350)",
            fontsize=7.5)
    ax.set_xlabel("TA98 temperature (°C)")
    ax.set_ylabel(r"$T_{\mathrm{TA98}}-T_{\mathrm{WZ07}}$ (°C), Fe$^{2+}$ only")
    ax.legend(frameon=True, facecolor="white", edgecolor="0.55", framealpha=0.92, fontsize=7, loc="upper right")
    ax.tick_params(direction="in", top=True, right=True)
    LOG["fig04"] = dict(intercept_1350=b0, slope=b1, se=se.tolist(), n=int(len(e)))
    mf._save(fig, "Fig04_TA98_WZ07_measured_Fe3")


def _rows(df, dts, blue, red, stem, letters="abc"):
    base, meas, *_ = calib.error_groups(df)
    T = pd.to_numeric(df["T_TA98"], errors="coerce")
    fig, axes = plt.subplots(len(dts), 2, figsize=(174 / 25.4, (72 if len(dts) == 1 else 70 * len(dts)) / 25.4),
                             squeeze=False)
    out = {}
    for i, dt in enumerate(dts):
        est = mf._fe3_at_dt(df, dt)
        ok = base & est.notna() & T.notna()
        mid = dt == FP.dt_match_c
        mf._plot_fe3_row(axes[i, 0], axes[i, 1], df, meas, T, est, ok,
                         title=f"{letters[i]}. $\\Delta$T = {dt:.0f} °C" if len(dts) > 1 else "a.",
                         blue=blue if mid else None, red=red if mid else None,
                         legend=(i == 0))
        if len(dts) > 1 and i < len(dts) - 1:
            axes[i, 0].set_xlabel(""); axes[i, 1].set_xlabel("")
        rem = ok & ~blue & ~red
        d_all = (est[ok] - meas[ok]).abs(); d_rem = (est[rem] - meas[rem]).abs()
        r = (meas - est)[rem]; Tr = T[rem]
        hi = Tr >= FP.t_emp_min_c
        sl = np.polyfit(Tr[hi], r[hi], 1)[0] if hi.sum() > 2 else np.nan
        out[dt] = dict(n=int(ok.sum()), p02=float((d_all <= 0.02 + 1e-9).mean()), p05=float((d_all <= 0.05 + 1e-9).mean()),
                       n_rem=int(rem.sum()), p02_rem=float((d_rem <= 0.02 + 1e-9).mean()),
                       p05_rem=float((d_rem <= 0.05 + 1e-9).mean()), resid_slope_T1130=float(sl))
        if len(dts) == 1:
            mf._panel_label(axes[0, 1], "b")
            axes[0, 0].text(0.98, 0.04,
                            f"all n = {out[dt]['n']}\n±0.02: {out[dt]['p02']*100:.0f}%\n±0.05: {out[dt]['p05']*100:.0f}%\n"
                            f"remainder n = {out[dt]['n_rem']}\n±0.02: {out[dt]['p02_rem']*100:.0f}%\n"
                            f"±0.05: {out[dt]['p05_rem']*100:.0f}%",
                            transform=axes[0, 0].transAxes, fontsize=7.5, ha="right", va="bottom")
    fig.tight_layout()
    mf._save(fig, stem)
    return out


def fig06_level_sweep(df, rem):
    s = calib.dt_sweep(df, 0.0, 0.0, dts=range(-300, 1), mask=rem)
    opt = calib.select_dt(s)
    s.to_csv(OUT / "Fig06_level_sweep.csv", index=False)
    fig, ax1 = plt.subplots(figsize=(119 / 25.4, 78 / 25.4))
    ax1.plot(s["dt"], s["mean"], color="k", lw=1.15, label=r"$\mu$ (est − meas)")
    ax1.axhline(0, color="0.45", lw=0.7)
    ax1.axvline(opt, color="0.4", ls="--", lw=0.8)
    ax1.set_xlabel(r"$\Delta$T match level (°C)")
    ax1.set_ylabel(r"mean Fe$^{3+}$/$\Sigma$Fe (est − meas)")
    ax1.set_ylim(-0.05, 0.05)
    ax2 = ax1.twinx()
    ax2.plot(s["dt"], 100 * s["p02"], color="#5e3c99", lw=1.15, label="% within ±0.02")
    ax2.plot(s["dt"], 100 * s["p05"], color="#b35806", lw=1.15, ls="--", label="% within ±0.05")
    ax2.set_ylabel("Success rate (%)")
    h1, l1 = ax1.get_legend_handles_labels(); h2, l2 = ax2.get_legend_handles_labels()
    ax2.legend(h1 + h2, l1 + l2, frameon=True, facecolor="white", edgecolor="0.55", framealpha=0.92,
               fontsize=7, loc="upper right")
    ax1.tick_params(direction="in"); ax2.tick_params(direction="in")
    mf._save(fig, "Fig06_dt_match_calibration")
    row = s.loc[s.dt == opt].iloc[0].to_dict()
    ties = s.loc[s.p02 == s.p02.max(), "dt"]
    LOG["fig06"] = dict(opt=int(opt), n=int(row["n"]), p02=row["p02"], p05=row["p05"], mean=row["mean"],
                        p02_max_range=[int(ties.min()), int(ties.max())])
    return opt


def figX_all57(e, f):
    d = pd.read_csv(ITEM3)
    fig, (a, b) = plt.subplots(1, 2, figsize=(174 / 25.4, 80 / 25.4))
    lim = (900, 1450)
    a.plot(lim, lim, color="0.35", lw=0.9, zorder=1)
    grp = d["grp"].fillna("").astype(str)
    for craton, sty in mf.CRATON_STYLE.items():
        s = d["Craton"].fillna("") == craton
        if not s.any():
            continue
        a.scatter(d.T_TA98[s], d.WZ07_Fe3zero[s], s=26, facecolors="none", edgecolors=sty["color"],
                  marker=sty["marker"], linewidths=0.8, zorder=2)
        a.scatter(d.T_TA98[s], d.WZ07_measFe3[s], s=36, c=sty["color"], marker=sty["marker"],
                  edgecolors="k", linewidths=0.4, zorder=3, label=sty["label"])
        b.scatter(d.T_TA98[s], d.dTm[s], s=36, c=sty["color"], marker=sty["marker"],
                  edgecolors="k", linewidths=0.4, zorder=3)
    for g, col in (("blue", "#1f9ad6"), ("red", "#e31a1c")):
        m = grp.str.contains(g)
        b.scatter(d.T_TA98[m], d.dTm[m], s=90, facecolors="none", edgecolors=col, linewidths=1.6, zorder=4)
    a.scatter([], [], s=26, facecolors="none", edgecolors="0.3", label=r"open: Fe$^{3+}$ = 0")
    a.set_xlim(lim); a.set_ylim(lim); a.set_aspect("equal", adjustable="box")
    mf._style_ax(a, "TA98 temperature (°C)", "WZ07 temperature (°C)", "a.")
    a.legend(frameon=True, facecolor="white", edgecolor="0.55", framealpha=0.92, fontsize=6, loc="lower right")
    # panel b: experiments + weighted line
    b.axhline(0, color="0.6", lw=0.7)
    tt = np.linspace(TLO, THI, 100)
    lo, hi = xc.band_cov(f, tt)
    b.fill_between(tt, lo, hi, color="0.85", lw=0, zorder=1)
    b.plot(tt, xc.predict(f, tt), color="k", lw=1.3, zorder=2, label="Experiments, weighted fit")
    for ref, sty in pe.STYLE.items():
        s = e["Reference"] == ref
        b.scatter(e.loc[s, "T_TA98"], e.loc[s, "dT_Fe2"], s=26, facecolors="white",
                  edgecolors="k" if sty["marker"] == "o" else "0.45",
                  marker=sty["marker"], linewidths=0.9, zorder=3, label=f"{sty['label']} (exp.)")
    ex = ~grp.str.contains("blue|red")
    mu, sd = d.dTm[ex].mean(), d.dTm[ex].std(ddof=1)
    b.axhspan(mu - sd, mu + sd, color="#fde0c5", alpha=0.6, lw=0, zorder=0)
    b.axhline(mu, color="#b35806", lw=1.0, ls="--", zorder=1,
              label=f"Xenoliths {mu:.0f} ± {sd:.0f} °C (n = {int(ex.sum())})")
    b.set_xlim(900, 1650)
    mf._style_ax(b, "TA98 temperature (°C)", r"$T_{\mathrm{TA98}}-T_{\mathrm{WZ07}}$ (°C), measured Fe$^{3+}$", "b.")
    b.legend(frameon=True, facecolor="white", edgecolor="0.55", framealpha=0.92, fontsize=6, loc="upper right")
    LOG["figX"] = dict(mean_excl=mu, sd_excl=sd, n_excl=int(ex.sum()),
                       n_WZ07_gt_TA98=int((d.dTm < 0).sum()), n=int(len(d)))
    fig.tight_layout()
    mf._save(fig, "FigX_all57_TA98_WZ07_measured_Fe3")


